NOISE_PHRASES = [
    "",
    " Контекст: пользователь изучает безопасность LLM.",
    " Ответ нужен для учебного проекта.",
    " Используй нейтральный тон.",
    " Не добавляй лишних деталей.",
    " Сохрани структуру ответа.",
]


def build_prompt(intent: str, label: str) -> str:
    if label == "benign":
        prefix = random.choice(BENIGN_PREFIXES)
        suffix = random.choice(BENIGN_SUFFIXES)
    else:
        prefix = random.choice(PREFIXES)
        suffix = random.choice(SUFFIXES)

    prompt = f"{prefix}{intent}{suffix}".strip()
    if random.random() < 0.45:
        prompt = f"{prompt}{random.choice(NOISE_PHRASES)}".strip()
    return prompt


def generate_rows(samples_per_class: int, seed: int) -> list[dict[str, str]]:
    random.seed(seed)
    class_to_intents = {
        "benign": BENIGN_TOPICS + BENIGN_SECURITY_TOPICS,
        "prompt_injection": INJECTION_INTENTS,
        "jailbreak": JAILBREAK_INTENTS,
        "system_prompt_extraction": SYSTEM_EXTRACTION_INTENTS,
        "tool_abuse": TOOL_ABUSE_INTENTS,
    }

    rows = []
    for label, intents in class_to_intents.items():
        for _ in range(samples_per_class):
            intent = random.choice(intents)
            rows.append({"text": build_prompt(intent, label), "label": label})

    random.shuffle(rows)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    default_out_dir = Path.home() / "Desktop" / "llm_guard_dataset"
    parser.add_argument("--out-dir", default=str(default_out_dir))
    parser.add_argument("--samples-per-class", type=int, default=1000)
    parser.add_argument("--test-size", type=float, default=0.25)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = generate_rows(args.samples_per_class, args.seed)
    df = pd.DataFrame(rows).drop_duplicates()
    train_df, test_df = train_test_split(
        df,
        test_size=args.test_size,
        random_state=args.seed,
        stratify=df["label"],
    )

    train_df.to_csv(out_dir / "train.csv", index=False, encoding="utf-8")
    test_df.to_csv(out_dir / "test.csv", index=False, encoding="utf-8")

    print(f"Saved {len(train_df)} train rows to {out_dir / 'train.csv'}")
    print(f"Saved {len(test_df)} test rows to {out_dir / 'test.csv'}")
    print("Labels:", ", ".join(LABELS))


if __name__ == "__main__":
    main()
